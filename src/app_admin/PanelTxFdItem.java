	private void _updateObject(Object srcObj) {
		if (!updFlg) return;

		if (srcObj instanceof javax.swing.JTextArea) {
			fdItm.setItmDesc(taDesc.getText().trim());
			return;
		}
		
		javax.swing.JTextField srcFld = (javax.swing.JTextField)srcObj;
		
		if (txtSeq == srcFld) {
			try {
				int num1 = Integer.parseInt(txtSeq.getText());
				fdItm.setItmSeq(num1);
			} catch (Exception e) {}
		}
		if (txtNamePos == srcFld) {
			fdItm.setItmNamePos(txtNamePos.getText().trim());
		}
		if (txtNameWeb == srcFld) {
			fdItm.setItmNameWeb(txtNameWeb.getText().trim());
		}
		if (txtPrice == srcFld) {
			try {
				double val1 = Double.parseDouble(txtPrice.getText());
				fdItm.setItmPrice(val1);
			} catch (Exception e) {}
		}
		if (txtTax == srcFld) {
			try {
				double val1 = Double.parseDouble(txtTax.getText());
				fdItm.setItmTax(val1);
			} catch (Exception e) {}
		}
	}

