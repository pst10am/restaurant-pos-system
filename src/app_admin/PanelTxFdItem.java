	@Override
	public JPanel getPanel() {
		return this;
	}

	@Override
	public boolean isDataValid() {
		try {
			Integer.parseInt(txtSeq.getText().trim());
			Double.parseDouble(txtPrice.getText().trim());
			Double.parseDouble(txtTax.getText().trim());
		} catch (Exception e) {
			return false;
		}
		return !txtNamePos.getText().trim().isEmpty();
	}

	@Override
	public Object getObject() {
		return fdItm;
	}

	@Override
	public void setObject(Object obj) {
		fdItm = null;
		if (null != obj) { 
			fdItm = (TxFdItem)obj;
		}
		updFlg = false;
		//
		txtSeq.setText(null==obj?"0":String.format("%d",fdItm.getItmSeq()));
		txtNamePos.setText(null==obj?"":fdItm.getItmNamePos());
		txtNameWeb.setText(null==obj?"":fdItm.getItmNameWeb());
		txtPrice.setText(null==obj?"0.00":String.format("%.2f", fdItm.getItmPrice()));
		txtTax.setText(null==obj?"0.00":String.format("%.2f", fdItm.getItmTax()));
		taDesc.setText(null==obj?"":fdItm.getItmDesc());
		cxBypass.setSelected(null==obj?false:fdItm.isBypassOpt());
		//
		txtSeq.setEnabled(null!=obj);
		txtNamePos.setEnabled(null!=obj);
		txtNameWeb.setEnabled(null!=obj);
		txtPrice.setEnabled(null!=obj);
		txtTax.setEnabled(null!=obj);
		taDesc.setEnabled(null!=obj);
		cxBypass.setEnabled(null!=obj);
		//
		updFlg = null != fdItm;
	}

	@Override
	public void actionPerformed(ActionEvent e) {
		if (!updFlg) return;
		//
		String cmd = e.getActionCommand();
		if ("update_bypass".equals(cmd)) {
			fdItm.setItmBypassOpt(cxBypass.isSelected());
		}
	}

	@Override
	public void insertUpdate(DocumentEvent de) {
		_updateObject(de.getDocument().getProperty("owner"));
	}
	@Override
	public void removeUpdate(DocumentEvent de) {
		_updateObject(de.getDocument().getProperty("owner"));
	}
	@Override
	public void changedUpdate(DocumentEvent de) {
		_updateObject(de.getDocument().getProperty("owner"));
	}
